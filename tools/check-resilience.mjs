import { execFileSync } from 'node:child_process';

const script = `async (page) => {
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('http://127.0.0.1:4174/');
  await page.locator('#journey[aria-busy="false"]').waitFor();
  await page.locator('.project[aria-hidden="false"]').waitFor();
  if (!await page.getByRole('button',{name:'모션 줄임 · 켜짐',exact:true}).isDisabled()) throw new Error('OS 모션 설정 미적용');
  await page.locator('#form').evaluate(el=>el.scrollIntoView());
  await page.locator('#type-sequence[data-letter-state="settled"]').waitFor();
  await page.emulateMedia({reducedMotion:'no-preference'});
  if (await page.getByRole('button',{name:'모션 줄이기',exact:true}).isDisabled()) throw new Error('OS 설정 해제 미적용');
  await page.route('**/pavilion-blockout.glb', route => route.abort());
  await page.goto('http://127.0.0.1:4174/');
  await page.locator('body.fallback').waitFor();
  await page.getByRole('link',{name:'작업 소개 먼저 보기 ↓',exact:true}).click();
  await page.locator('.work-image img').evaluate(img=>img.decode());
  await page.screenshot({path:'output/playwright/site-fallback.png'});
  await page.unroute('**/pavilion-blockout.glb');
  await page.route('**/pavilion-blockout.glb', async route => { await new Promise(r=>setTimeout(r,4000)); await route.abort(); });
  await page.goto('http://127.0.0.1:4174/');
  await page.evaluate(() => { const s=document.querySelector('#type-sequence'); window.scrollTo(0, s.offsetTop + (s.offsetHeight-innerHeight)*.9); });
  await page.locator('#type-sequence[data-letter-state="settled"]').waitFor();
  await page.locator('body.fallback').waitFor({timeout:8000});
  await page.waitForTimeout(500);
  if (await page.locator('#type-sequence').getAttribute('data-letter-state') !== 'settled') throw new Error('늦은 GLB 실패 뒤 FORM 착지 해제');
  await page.unroute('**/pavilion-blockout.glb');
  await page.goto('http://127.0.0.1:4174/');
  await page.locator('#journey[aria-busy="false"]').waitFor();
  if (await page.getByRole('status').count()) throw new Error('진행률이 라이브 리전으로 노출');
  const noJs = await page.context().browser().newContext({javaScriptEnabled:false});
  await noJs.route('http://127.0.0.1:4174/**', route => { const path=new URL(route.request().url()).pathname; route.fulfill({path:${JSON.stringify(process.cwd()+'/dist')}+(path==='/'?'/index.html':decodeURIComponent(path))}); });
  const plain = await noJs.newPage();
  await plain.goto('http://127.0.0.1:4174/');
  const covered = await plain.evaluate(()=>document.elementFromPoint(innerWidth/2,innerHeight/2)?.closest('noscript'));
  await noJs.close();
  if (covered) throw new Error('JS 비활성 화면을 noscript 상자가 가림');
  for (const width of [320,768,1440]) {
    await page.setViewportSize({width,height:900});
    await page.getByRole('link',{name:'Contact',exact:true}).click();
    if (await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw new Error('가로 넘침 '+width);
  }
  await page.getByRole('link',{name:'Morrow 시작으로',exact:true}).click();
  await page.waitForFunction(()=>scrollY===0);
  await page.keyboard.press('Tab');
  return {osReducedMotion:'실시간 설정/해제 통과',glbFailure:'작업 소개 우회 및 이미지 표시 통과',lateGlbFailure:'4초 지연 실패 뒤 FORM 착지 유지',progress:'라이브 리전 아님',noscript:'본문 가림 없음',widths:[320,390,768,1440]};
}`;
const output = execFileSync('npx', ['--offline', '--package', '@playwright/cli', 'playwright-cli', '--session', 'aether-full', 'run-code', script], { encoding: 'utf8', timeout: 90000 });
console.log(output.split('### Ran Playwright code')[0]);
